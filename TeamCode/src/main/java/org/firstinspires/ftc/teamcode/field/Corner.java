package org.firstinspires.ftc.teamcode.field;

/**
 * The four relocalize spots, one in each corner of the field. In each one the
 * intake is flat on an alliance wall and a side is flat on a side wall. NEAR is
 * on our own alliance wall (intake facing the driver), FAR on the other
 * alliance's wall (intake facing away). Left and right are as the driver sees
 * them from the ALLIANCE AREA.
 */
public enum Corner {
    NEAR_LEFT,
    NEAR_RIGHT,
    FAR_LEFT,
    FAR_RIGHT
}
